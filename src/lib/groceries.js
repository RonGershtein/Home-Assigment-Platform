const norm = (s) => s.trim().replace(/[׳`’]/g, "'").replace(/["״]/g, "").replace(/\s+/g, " ");

export const GROCERIES = RAW.map(([name, icon, category, common]) => ({ name, icon, category, common: !!common, key: norm(name) }));
// הארוך קודם: "חלב שקדים" לפני "חלב", "אבקת גריל עוף" לפני "עוף"
const BY_LENGTH = [...GROCERIES].sort((a, b) => b.key.length - a.key.length);
const EXACT = new Map(GROCERIES.map((g) => [g.key, g]));

const cache = new Map();
// מוצא את המוצר בקטלוג: התאמה מדויקת, אחרת המילה הארוכה ביותר שמופיעה בשם (כמילה שלמה)
export function matchGrocery(name) {
  if (!name) return null;
  const n = norm(name);
  if (cache.has(n)) return cache.get(n);
  let hit = EXACT.get(n) ?? null;
  if (!hit) {
    const padded = ` ${n} `;
    hit = BY_LENGTH.find((g) => padded.includes(` ${g.key} `)) ?? BY_LENGTH.find((g) => g.key.length >= 3 && n.startsWith(g.key)) ?? null;
  }
  cache.set(n, hit);
  return hit;
}

export const COMMON_GROCERIES = GROCERIES.filter((g) => g.common);
