export const FOODS = RAW.map(([key, name, icon, category, serving, kcal, protein]) => ({ key, name, icon, category, serving, kcal, protein }));
const byKey = new Map(FOODS.map((f) => [f.key, f]));
export const foodByKey = (k) => byKey.get(k);

// אותיות סופיות → רגילות, כדי ש"חלבו" ימצא "חלבון" וכו'
const FINALS = { ך: "כ", ם: "מ", ן: "נ", ף: "פ", ץ: "צ" };
export const normalize = (s) =>
  (s || "")
    .toLowerCase()
    .replace(/[ךםןףץ]/g, (c) => FINALS[c])
    .replace(/['"״׳`]/g, "")
    .trim();

export function searchFoods(query, limit = 30) {
  const q = normalize(query);
  if (!q) return [];
  const words = q.split(/\s+/);
  const scored = [];
  for (const f of FOODS) {
    const n = normalize(f.name);
    if (!words.every((w) => n.includes(w))) continue;
    scored.push([n.startsWith(q) ? 0 : n.indexOf(q) >= 0 ? 1 : 2, f]);
  }
  return scored.sort((a, b) => a[0] - b[0]).slice(0, limit).map((x) => x[1]);
}
